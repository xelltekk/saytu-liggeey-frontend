import { createRequire } from 'node:module'
import { join } from 'node:path'
import { homedir } from 'node:os'
import { mkdir } from 'node:fs/promises'
import assert from 'node:assert/strict'

const require = createRequire(import.meta.url)
const runtime = join(homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules')
const { chromium } = require(join(runtime, 'playwright'))
const { expect } = require(join(runtime, 'playwright/test'))
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1040 } })
const errors = [], networkLeaks = []
page.on('pageerror', error => errors.push(error.message))
await page.route('**/api/**', route => { networkLeaks.push(route.request().url()); return route.abort() })
await page.addInitScript(() => localStorage.setItem('xelltekk_user', JSON.stringify({ id: 999, modules_context: { fixture: 'ancien catalogue à retirer' } })))
await mkdir('output', { recursive: true })

try {
  await page.goto('http://127.0.0.1:5187/tests/modules-harness.html')
  await expect(page.getByRole('heading', { name: 'Modules', exact: true, level: 1 })).toBeVisible()
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('xelltekk_user')).modules_context), undefined)
  const search = page.getByRole('searchbox', { name: 'Rechercher un module' })
  await search.fill('démonstration')
  const knowledge = page.getByRole('switch', { name: 'Activer Connaissances de démonstration', exact: true })
  await expect(knowledge).toBeEnabled()
  await expect(knowledge).not.toBeChecked()
  await page.screenshot({ path: 'output/modules-phase3-desktop.png', fullPage: true })

  await page.getByRole('button', { name: 'Paramètres de Connaissances de démonstration', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByText('Ce module ne dispose pas de paramètres dédiés pour le moment.')).toBeVisible()
  await page.getByRole('button', { name: 'Fermer', exact: true }).click()
  await knowledge.click()
  await expect(page.getByRole('heading', { name: 'Dépendances à activer également' })).toBeVisible()
  await expect(page.getByRole('dialog').getByText('Contacts de démonstration', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Confirmer', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('switch', { name: 'Désactiver Connaissances de démonstration', exact: true })).toBeChecked()
  await expect(page.getByRole('switch', { name: 'Désactiver Contacts de démonstration', exact: true })).toBeChecked()
  await expect(page.getByRole('cell', { name: 'Administrateur #7001', exact: true })).toBeVisible()
  console.log('PASS aperçu dépendances, confirmation, activation et audit via API entièrement fictive')

  await page.getByRole('switch', { name: 'Désactiver Contacts de démonstration', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Des modules actifs en dépendent' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Confirmer', exact: true })).toHaveCount(0)
  await page.screenshot({ path: 'output/modules-phase3-dependencies.png', fullPage: true })
  await page.getByRole('button', { name: 'Annuler', exact: true }).click()
  console.log('PASS désactivation dépendance bloquée avant toute écriture')

  await search.fill('SAV hors abonnement')
  await expect(page.getByRole('switch', { name: 'Activer SAV hors abonnement', exact: true })).toBeDisabled()
  await search.fill('Facturation')
  await expect(page.getByRole('switch', { name: 'Désactiver Facturation', exact: true })).toBeDisabled()
  await expect(page.getByRole('switch', { name: 'Désactiver Facturation', exact: true })).toBeChecked()
  assert.equal(await page.getByRole('heading', { name: 'Administration plateforme', exact: true }).count(), 0)
  console.log('PASS module hors abonnement indisponible, modules historiques verrouillés et plateforme masquée')

  await search.fill('démonstration')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('.app-shell')).toHaveAttribute('data-device', 'mobile')
  // Ouvre puis ferme le tiroir via un vrai lien pour attendre la fin de sa transition.
  const menuToggle = page.getByRole('button', { name: 'Ouvrir ou réduire le menu principal' })
  await menuToggle.click()
  await page.locator('#main-sidebar').getByRole('link', { name: 'Modules', exact: true }).click()
  await expect(menuToggle).toHaveAttribute('aria-expanded', 'false')
  await expect.poll(async () => { const box = await page.locator('#main-sidebar').boundingBox(); return Math.round(box.x + box.width) }).toBeLessThanOrEqual(0)
  await expect(search).toBeVisible()
  const titleBox = await page.getByRole('heading', { name: 'Connaissances de démonstration', level: 3, exact: true }).boundingBox()
  const toggleBox = await page.getByRole('switch', { name: 'Désactiver Connaissances de démonstration', exact: true }).boundingBox()
  assert(titleBox.x + titleBox.width <= toggleBox.x - 4, 'le titre ne doit pas chevaucher le commutateur')
  await expect(page.locator('article').filter({ hasText: 'Administrateur #7001' })).toBeVisible()
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  assert.equal(overflow, false, 'la page ne doit pas défiler horizontalement à 390px')
  await page.screenshot({ path: 'output/modules-phase3-mobile.png', fullPage: true })
  console.log('PASS rendu 390px sans débordement horizontal')

  await page.setViewportSize({ width: 1440, height: 1040 })
  await page.evaluate(() => window.__modulesHarness.router.push('/metier/connaissances'))
  await expect(page.getByRole('heading', { name: 'Connaissances de démonstration', exact: true, level: 1 })).toBeVisible()
  await page.evaluate(() => window.__modulesHarness.remoteDisable('connaissances'))
  await expect(page).toHaveURL(/\/module-indisponible$/)
  await expect(page.getByRole('heading', { name: 'Rubrique indisponible', exact: true, level: 1 })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Connaissances de démonstration', exact: true, level: 1 })).toHaveCount(0)
  console.log('PASS écran déjà ouvert retiré et navigation directe protégée après OFF distant')
  await page.evaluate(async () => {
    const harness = window.__modulesHarness
    const original = harness.state.requests.find(request => request.url === '/configuration/modules/apply').body
    await harness.store.applyChange(original)
  })
  assert.equal(await page.evaluate(() => window.__modulesHarness.store.revision), 3)
  assert.equal(await page.evaluate(() => window.__modulesHarness.store.allows('connaissances')), false)
  console.log('PASS rejeu ancien sans recul de révision ni réactivation locale')

  await page.evaluate(() => window.__modulesHarness.router.push('/metier/connaissances'))
  await expect(page).toHaveURL(/\/module-indisponible$/)
  const privateBefore = await page.evaluate(() => window.__modulesHarness.state.requests.filter(request => ['/modules/context', '/auth/me'].includes(request.url)).length)
  await page.evaluate(() => window.__modulesHarness.router.push('/portail-clients'))
  await expect(page).toHaveURL(/\/portail-clients$/)
  const privateAfter = await page.evaluate(() => window.__modulesHarness.state.requests.filter(request => ['/modules/context', '/auth/me'].includes(request.url)).length)
  assert.equal(privateAfter, privateBefore, 'le portail invité ne charge pas de contexte privé')
  console.log('PASS portail invité séparé du contexte privé')

  await page.evaluate(() => window.__modulesHarness.auth.fetchMe())
  const storedUser = await page.evaluate(() => JSON.parse(localStorage.getItem('xelltekk_user')))
  assert.equal(storedUser.modules_context, undefined)
  const contextsBeforeNavigation = await page.evaluate(() => window.__modulesHarness.state.requests.filter(request => request.url === '/modules/context').length)
  await page.evaluate(() => window.__modulesHarness.router.push('/configuration/modules'))
  await expect(page.getByRole('heading', { name: 'Modules', exact: true, level: 1 })).toBeVisible()
  const contextsAfterNavigation = await page.evaluate(() => window.__modulesHarness.state.requests.filter(request => request.url === '/modules/context').length)
  assert.equal(contextsAfterNavigation, contextsBeforeNavigation, 'le contexte auth évite une lecture privée redondante')
  await page.evaluate(() => { const auth = window.__modulesHarness.auth; auth.acceptSessionUser({ ...auth.user, name: 'Profil de démonstration actualisé' }) })
  assert.equal(await page.evaluate(() => window.__modulesHarness.auth.user.tenant.id), 7)
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('xelltekk_user')).modules_context), undefined)
  console.log('PASS ancien stockage nettoyé, profil partiel préservé, contexte auth uniquement en mémoire et aucune seconde requête inutile')

  assert.deepEqual(errors, [])
  assert.deepEqual(networkLeaks, [])
  const writes = await page.evaluate(() => window.__modulesHarness.state.requests.filter(request => request.url === '/configuration/modules/apply'))
  assert.equal(writes.length, 2)
  assert.equal(new Set(writes.map(request => request.body.request_id)).size, 1)
  assert.equal(await page.evaluate(() => window.__modulesHarness.state.events.length), 1)
  assert.deepEqual(writes[0].body.confirmed_dependencies, ['contacts'])
  console.log('PASS une seule mutation fictive, aucune API réelle, aucune erreur JavaScript')
} catch (cause) {
  console.error('Erreurs JavaScript :', errors)
  console.error('État final :', await page.evaluate(() => ({url: location.href, revision: window.__modulesHarness?.store.revision, knowledge: window.__modulesHarness?.store.context?.modules.find(module => module.key === 'connaissances'), requests: window.__modulesHarness?.state.requests.slice(-6)})))
  await page.screenshot({ path: 'output/modules-phase3-failure.png', fullPage: true })
  throw cause
} finally { await browser.close() }
