import { createRequire } from 'node:module'
import { join } from 'node:path'
import assert from 'node:assert/strict'
const require = createRequire(import.meta.url)
const { chromium } = require(join(process.env.SAYTU_TEST_RUNTIME, 'playwright'))
const browser = await chromium.launch({ headless: true, channel: 'msedge' })
try {
  const page = await browser.newPage()
  const errors = [], native = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('dialog', d => { native.push(d.message()); d.dismiss() })
  await page.goto('http://127.0.0.1:5179/tests/browser/dialogs.html')
  await page.getByRole('button', { name: 'Tester confirmation' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.waitFor()
  assert.match(await dialog.innerText(), /Quitter la comparaison/)
  await page.keyboard.press('Shift+Tab')
  assert.equal(await page.evaluate(() => document.activeElement.textContent.trim()), 'OK')
  await page.keyboard.press('Escape')
  await page.waitForFunction(() => document.querySelector('output').textContent === 'false')
  assert.equal(await page.evaluate(() => document.activeElement.textContent), 'Tester confirmation')
  await page.getByRole('button', { name: 'Tester confirmation' }).click()
  await dialog.getByRole('button', { name: 'OK', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('output').textContent === 'true')
  await page.getByRole('button', { name: 'Tester saisie' }).click()
  assert.equal(await page.getByLabel('Votre réponse').inputValue(), 'Contrôle stock validé')
  await page.getByLabel('Votre réponse').fill('Vérifié')
  await page.getByLabel('Votre réponse').press('Enter')
  await page.waitForFunction(() => document.querySelector('output').textContent === '"Vérifié"')
  await page.setViewportSize({ width: 375, height: 667 })
  await page.getByRole('button', { name: 'Tester saisie' }).click()
  const box = await dialog.boundingBox()
  assert.ok(box.x >= 0 && box.x + box.width <= 375)
  await dialog.getByRole('button', { name: 'Annuler', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('output').textContent === 'null')
  await page.goto('http://127.0.0.1:5179/tests/browser/leasing.html')
  await page.getByLabel('Date du relevé précédent', { exact: true }).fill('2026-10-01')
  await page.getByRole('link', { name: '← Retour liste' }).click()
  await dialog.getByRole('button', { name: 'Annuler', exact: true }).click()
  assert.equal(await page.getByLabel('Date du relevé précédent', { exact: true }).inputValue(), '2026-10-01')
  await page.getByRole('link', { name: '← Retour liste' }).click()
  await dialog.getByRole('button', { name: 'OK', exact: true }).click()
  await page.getByText('Liste de test', { exact: true }).waitFor()
  assert.deepEqual(errors, []); assert.deepEqual(native, [])
  console.log('PASS: confirmation, cancellation, prompt, keyboard focus, mobile and no native dialogs')
} finally { await browser.close() }
